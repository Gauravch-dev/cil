"""## 5. Scaling, peak labels, and training batches

Every electrical signal is standardized using **training data only**.
The context scaler is also fitted using training examples only.

A target is labelled as a high-demand event when its active power is above
the **training 90th percentile**.

The final multi-task model receives two learning signals:

### Regression
Predict future power.

Peak targets receive `2.5×` regression sample weight so a large miss during a
rare high-load event matters more during training.

### Peak classification
Predict whether the future target is above the training peak threshold.

Peak targets receive `4×` classification weight to fight the roughly 90/10
class imbalance.

Validation and test metrics are always reported **without these weights**.
The weights affect learning only.

"""

