"""## 3. Causal multivariate preprocessing

Each 15-minute value is the mean of a **completed** interval. For each
electrical feature, an interval is considered genuinely observed only when
all 15 minute readings are valid.

For model **inputs**, an incomplete interval may be forward-filled for at
most four 15-minute bins (one hour), using past values only. Longer gaps
remain missing and any history window containing them is excluded.

The model also receives an `electrical_observed_fraction` value at every time
step, telling it what fraction of the seven electrical signals were genuinely
observed rather than filled.

The **target is never imputed**: `Global_active_power` at the future target
interval must be fully observed.

This preserves the same forecasting semantics as Version 1 while giving the
LSTM richer real-world electrical context.

"""

def prepare_multivariate(minute_frame, features, max_forward_fill=4):
    if not minute_frame.index.is_unique or not minute_frame.index.is_monotonic_increasing:
        raise ValueError("Minute readings must have unique, sorted timestamps.")

    minute_frame = minute_frame[features].copy()

    bins = minute_frame.resample("15min", closed="left", label="right")
    means = bins.mean()
    counts = bins.count()

    observed = counts.eq(15)
    actual = means.where(observed)
    input_values = actual.ffill(limit=max_forward_fill)

    out = pd.DataFrame(index=means.index)

    for feature in features:
        out[f"actual_{feature}"] = actual[feature]
        out[f"input_{feature}"] = input_values[feature]
        out[f"observed_{feature}"] = observed[feature].astype(float)

    # Convenient aliases used by the target/context/evaluation code.
    out["actual_kw"] = out[f"actual_{TARGET_FEATURE}"]
    out["input_kw"] = out[f"input_{TARGET_FEATURE}"]
    out["observed"] = out[f"observed_{TARGET_FEATURE}"].astype(bool)

    # One compact data-quality signal for the LSTM history.
    out["electrical_observed_fraction"] = observed[features].mean(axis=1).astype(float)

    return out

