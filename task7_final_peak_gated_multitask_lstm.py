"""## 6. FINAL architecture — peak-gated multi-task LSTM

The final architecture explicitly models the problem discovered in V2.

### Shared temporal representation

```text
96 × multivariate history
        ↓
LSTM 64
        ↓
Dropout
        ↓
LSTM 32
        ↓
Context features
        ↓
Dense shared representation
```

### Two learning tasks

The shared representation produces:

1. **Peak probability**
   - “Is the target one hour ahead likely to be high demand?”

2. **Power forecast**
   - a normal/base forecast,
   - a learned positive peak adjustment.

The final forecast is conceptually:

```text
final forecast
=
base forecast
+
peak probability × peak adjustment
```

So when the classifier sees little evidence of a peak, the peak correction is
small. When it sees strong evidence, the model can raise its forecast.

The regression loss is **Huber loss**, which is more robust to extremely large
errors than pure MSE while still learning from them. Peak examples are also
up-weighted.

The peak-classification loss is an auxiliary binary cross-entropy objective.
It shapes the same LSTM representation but does not replace the regression
target.

"""

