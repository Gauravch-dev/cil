def valid_target_indices(
    power_frame,
    context_frame,
    sequence_length=96,
    horizon=4
):
    targets = np.arange(
        len(power_frame),
        dtype=np.int64
    )

    ends = targets - horizon + 1
    starts = ends - sequence_length

    row_missing = (
        power_frame[HISTORY_INPUT_COLUMNS]
        .isna()
        .any(axis=1)
        .to_numpy()
        .astype(np.int64)
    )

    cumulative = np.r_[
        0,
        np.cumsum(row_missing)
    ]

    bounds_ok = starts >= 0

    safe_start = np.maximum(starts, 0)
    safe_end = np.maximum(ends, 0)

    window_ok = (
        cumulative[safe_end]
        - cumulative[safe_start]
    ) == 0

    context_ok = np.isfinite(
        context_frame.to_numpy()
    ).all(axis=1)

    # The target itself must be genuinely measured.
    target_ok = power_frame[
        "observed"
    ].to_numpy()

    eligible = (
        bounds_ok
        & window_ok
        & context_ok
        & target_ok
    )

    return targets[eligible]


