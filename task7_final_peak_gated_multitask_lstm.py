"""## 4. Final feature set and chronological partitions

The history branch still receives 96 previous 15-minute intervals (24 hours)
of real electrical measurements and cyclical calendar information.

The final phase strengthens the **context branch** with features aimed at
detecting a developing peak.

### Short-term ramps
Examples:

- change in active power over 15 minutes,
- change over 30 minutes,
- change over 1 hour,
- change in current (`Global_intensity`) over 15 minutes and 1 hour.

These tell the model whether electricity demand is **rising**, not only what
its current level is.

### Rolling behaviour

For active power:

- rolling mean over 30 min, 1 h, 2 h, 4 h, 24 h,
- rolling standard deviation over 1 h, 4 h, 24 h,
- rolling maximum over 1 h, 4 h, 24 h,
- rolling minimum and range over 1 h and 4 h.

For current and sub-metering:

- latest value,
- short-term mean,
- short-term maximum,
- short-term ramp.

### Seasonal lags

The model receives the corresponding target slot from:

- yesterday,
- two days ago,
- one week ago.

All meter-derived features use information available **at or before the
forecast origin**. Future calendar information is allowed because the future
clock/day/month is already known.

"""

def calendar_features(index):
    hour = index.hour + index.minute / 60.0

    return pd.DataFrame({
        "hour_sin": np.sin(2 * np.pi * hour / 24),
        "hour_cos": np.cos(2 * np.pi * hour / 24),

        "dow_sin": np.sin(2 * np.pi * index.dayofweek / 7),
        "dow_cos": np.cos(2 * np.pi * index.dayofweek / 7),

        "month_sin": np.sin(2 * np.pi * (index.month - 1) / 12),
        "month_cos": np.cos(2 * np.pi * (index.month - 1) / 12),

        "weekend": (index.dayofweek >= 5).astype(float),
    }, index=index)


def build_context(power_frame, horizon=4):
    p = power_frame["input_kw"]

    # At target row t, p.shift(horizon) is the LAST value known at
    # forecast origin t-horizon.
    latest = p.shift(horizon)
    lag_15m = p.shift(horizon + 1)
    lag_30m = p.shift(horizon + 2)
    lag_1h = p.shift(horizon + 4)
    lag_2h = p.shift(horizon + 8)

    frame = pd.DataFrame(index=power_frame.index)

    # ----------------------------------------------------------
    # Level / lag features
    # ----------------------------------------------------------
    frame["latest_kw"] = latest
    frame["15min_before_origin_kw"] = lag_15m
    frame["30min_before_origin_kw"] = lag_30m
    frame["one_hour_before_origin_kw"] = lag_1h
    frame["two_hours_before_origin_kw"] = lag_2h

    # ----------------------------------------------------------
    # Ramps: positive means load has risen.
    # ----------------------------------------------------------
    frame["ramp_15min_kw"] = latest - lag_15m
    frame["ramp_30min_kw"] = latest - lag_30m
    frame["ramp_1hour_kw"] = latest - lag_1h
    frame["ramp_2hour_kw"] = latest - lag_2h

    # ----------------------------------------------------------
    # Seasonal target-slot lags.
    # These values happened well before the current forecast.
    # ----------------------------------------------------------
    frame["target_slot_previous_day_kw"] = p.shift(96)
    frame["target_slot_two_days_ago_kw"] = p.shift(192)
    frame["target_slot_previous_week_kw"] = p.shift(672)

    # ----------------------------------------------------------
    # Rolling active-power summaries ending at forecast origin.
    # ----------------------------------------------------------
    windows = {
        "30min": 2,
        "1hour": 4,
        "2hours": 8,
        "4hours": 16,
        "24hours": 96,
    }

    for name, window in windows.items():
        rolling = p.rolling(window)

        frame[f"mean_previous_{name}_kw"] = (
            rolling.mean().shift(horizon)
        )

        if window >= 4:
            frame[f"std_previous_{name}_kw"] = (
                rolling.std(ddof=0).shift(horizon)
            )

        frame[f"max_previous_{name}_kw"] = (
            rolling.max().shift(horizon)
        )

        if window <= 16:
            frame[f"min_previous_{name}_kw"] = (
                rolling.min().shift(horizon)
            )
            frame[f"range_previous_{name}_kw"] = (
                frame[f"max_previous_{name}_kw"]
                - frame[f"min_previous_{name}_kw"]
            )

    frame["observed_fraction_previous_day"] = (
        power_frame["electrical_observed_fraction"]
        .rolling(96)
        .mean()
        .shift(horizon)
    )

    # ----------------------------------------------------------
    # Other electrical signals.
    # ----------------------------------------------------------
    for feature in ELECTRICAL_FEATURES[1:]:
        series = power_frame[f"input_{feature}"]
        frame[f"latest_{feature}"] = series.shift(horizon)

    intensity = power_frame["input_Global_intensity"]

    frame["intensity_15min_before_origin"] = (
        intensity.shift(horizon + 1)
    )
    frame["intensity_1hour_before_origin"] = (
        intensity.shift(horizon + 4)
    )

    frame["ramp_15min_Global_intensity"] = (
        intensity.shift(horizon)
        - intensity.shift(horizon + 1)
    )
    frame["ramp_1hour_Global_intensity"] = (
        intensity.shift(horizon)
        - intensity.shift(horizon + 4)
    )

    frame["mean_previous_hour_Global_intensity"] = (
        intensity.rolling(4).mean().shift(horizon)
    )
    frame["max_previous_4hours_Global_intensity"] = (
        intensity.rolling(16).max().shift(horizon)
    )

    # ----------------------------------------------------------
    # Aggregate sub-metering activity.
    # ----------------------------------------------------------
    submeter_total = (
        power_frame["input_Sub_metering_1"]
        + power_frame["input_Sub_metering_2"]
        + power_frame["input_Sub_metering_3"]
    )

    frame["latest_submeter_total"] = (
        submeter_total.shift(horizon)
    )
    frame["submeter_total_15min_before_origin"] = (
        submeter_total.shift(horizon + 1)
    )
    frame["ramp_15min_submeter_total"] = (
        submeter_total.shift(horizon)
        - submeter_total.shift(horizon + 1)
    )
    frame["mean_previous_hour_submeter_total"] = (
        submeter_total.rolling(4).mean().shift(horizon)
    )
    frame["max_previous_4hours_submeter_total"] = (
        submeter_total.rolling(16).max().shift(horizon)
    )

    # Target calendar features are known in advance.
    frame = frame.join(
        calendar_features(frame.index).add_prefix("target_")
    )

    return frame


