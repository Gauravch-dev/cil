def build_regression_model(
    kind,
    name,
    units=(32, 16),
    dropout=0.15,
    l2_strength=1e-5,
    learning_rate=1e-3,
):

    history_input = keras.Input(
        (
            SEQUENCE_LENGTH,
            len(HISTORY_FEATURES)
        ),
        name="history"
    )

    context_input = keras.Input(
        (
            len(CONTEXT_FEATURES),
        ),
        name="context"
    )

    penalty = regularizers.l2(
        l2_strength
    )

    if kind == "lstm":

        h = layers.LSTM(
            units[0],
            return_sequences=True,
            kernel_regularizer=penalty,
            name="lstm_temporal_features"
        )(history_input)

        h = layers.Dropout(
            dropout,
            name="sequence_dropout"
        )(h)

        h = layers.LSTM(
            units[1],
            return_sequences=False,
            kernel_regularizer=penalty,
            name="lstm_summary"
        )(h)

        h = layers.Dropout(
            dropout,
            name="summary_dropout"
        )(h)

    else:

        h = layers.Flatten(
            name="flatten_history"
        )(history_input)

    h = layers.Concatenate(
        name="history_and_context"
    )([
        h,
        context_input
    ])

    h = layers.Dense(
        64 if kind == "mlp" else 32,
        activation="relu",
        kernel_regularizer=penalty,
        name="dense_features"
    )(h)

    h = layers.Dropout(
        dropout
    )(h)

    if kind == "mlp":

        h = layers.Dense(
            32,
            activation="relu",
            kernel_regularizer=penalty
        )(h)

    output = layers.Dense(
        1,
        name="forecast_scaled"
    )(h)

    network = keras.Model(
        inputs={
            "history": history_input,
            "context": context_input,
        },
        outputs=output,
        name=name,
    )

    network.compile(
        optimizer=keras.optimizers.Adam(
            learning_rate=learning_rate,
            clipnorm=1.0,
        ),
        loss="mse",
        metrics=[
            keras.metrics.MeanSquaredError(
                name="mse"
            ),
            keras.metrics.MeanAbsoluteError(
                name="mae"
            ),
        ],
    )

    return network


def build_peak_gate_model(
    name="lstm_final_peak_gate",
    units=(64, 32),
    dropout=0.20,
    l2_strength=1e-4,
    learning_rate=5e-4,
):

    history_input = keras.Input(
        (
            SEQUENCE_LENGTH,
            len(HISTORY_FEATURES)
        ),
        name="history"
    )

    context_input = keras.Input(
        (
            len(CONTEXT_FEATURES),
        ),
        name="context"
    )

    penalty = regularizers.l2(
        l2_strength
    )

    # --------------------------------------------------------
    # Temporal representation
    # --------------------------------------------------------
    h = layers.LSTM(
        units[0],
        return_sequences=True,
        kernel_regularizer=penalty,
        name="lstm_temporal_features"
    )(history_input)

    h = layers.Dropout(
        dropout,
        name="sequence_dropout"
    )(h)

    h = layers.LSTM(
        units[1],
        return_sequences=False,
        kernel_regularizer=penalty,
        name="lstm_summary"
    )(h)

    h = layers.Dropout(
        dropout,
        name="summary_dropout"
    )(h)

    # --------------------------------------------------------
    # Combine temporal and engineered context
    # --------------------------------------------------------
    shared = layers.Concatenate(
        name="history_and_context"
    )([
        h,
        context_input
    ])

    shared = layers.Dense(
        64,
        activation="relu",
        kernel_regularizer=penalty,
        name="shared_dense"
    )(shared)

    shared = layers.Dropout(
        0.15,
        name="shared_dropout"
    )(shared)

    shared = layers.Dense(
        32,
        activation="relu",
        kernel_regularizer=penalty,
        name="shared_dense_2"
    )(shared)

    # --------------------------------------------------------
    # Auxiliary task: probability of high demand
    # --------------------------------------------------------
    peak_probability = layers.Dense(
        1,
        activation="sigmoid",
        name="peak_probability"
    )(shared)

    # --------------------------------------------------------
    # Regression:
    # normal/base forecast + gated positive peak adjustment
    # --------------------------------------------------------
    base_forecast = layers.Dense(
        1,
        name="base_forecast_scaled"
    )(shared)

    peak_adjustment = layers.Dense(
        1,
        activation="softplus",
        name="peak_adjustment_scaled"
    )(shared)

    gated_adjustment = layers.Multiply(
        name="gated_peak_adjustment"
    )([
        peak_probability,
        peak_adjustment
    ])

    forecast = layers.Add(
        name="forecast_scaled"
    )([
        base_forecast,
        gated_adjustment
    ])

    network = keras.Model(
        inputs={
            "history": history_input,
            "context": context_input,
        },
        outputs={
            "forecast_scaled":
                forecast,

            "peak_probability":
                peak_probability,
        },
        name=name,
    )

    network.compile(
        optimizer=keras.optimizers.Adam(
            learning_rate=learning_rate,
            clipnorm=1.0,
        ),

        loss={
            "forecast_scaled":
                keras.losses.Huber(
                    delta=1.0
                ),

            "peak_probability":
                keras.losses.BinaryCrossentropy(),
        },

        loss_weights={
            "forecast_scaled":
                1.0,

            "peak_probability":
                AUXILIARY_PEAK_LOSS_WEIGHT,
        },

        metrics={
            "forecast_scaled": [
                keras.metrics.MeanSquaredError(
                    name="mse"
                ),
                keras.metrics.MeanAbsoluteError(
                    name="mae"
                ),
            ],

            "peak_probability": [
                keras.metrics.AUC(
                    name="auc"
                ),
                keras.metrics.Precision(
                    name="precision"
                ),
                keras.metrics.Recall(
                    name="recall"
                ),
            ],
        },
    )

    return network


