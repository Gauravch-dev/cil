def regression_metrics(
    actual,
    prediction
):

    actual = np.asarray(
        actual
    ).ravel()

    prediction = np.asarray(
        prediction
    ).ravel()

    assert (
        len(actual)
        == len(prediction)
    )

    assert np.isfinite(
        actual
    ).all()

    assert np.isfinite(
        prediction
    ).all()

    mse = mean_squared_error(
        actual,
        prediction
    )

    return {
        "MAE_kW":
            float(
                mean_absolute_error(
                    actual,
                    prediction
                )
            ),

        "MSE_kW2":
            float(mse),

        "RMSE_kW":
            float(np.sqrt(mse)),

        "R2":
            float(
                r2_score(
                    actual,
                    prediction
                )
            ),
    }


def prediction_outputs(
    network,
    ids
):

    outputs = network.predict(
        make_feature_dataset(ids),
        verbose=0
    )

    peak_probability = None

    if isinstance(
        outputs,
        dict
    ):

        scaled = outputs[
            "forecast_scaled"
        ]

        peak_probability = outputs[
            "peak_probability"
        ].ravel()

    elif isinstance(
        outputs,
        (list, tuple)
    ):

        # Safe fallback if a Keras version returns a list.
        name_to_output = dict(
            zip(
                network.output_names,
                outputs
            )
        )

        scaled = name_to_output[
            "forecast_scaled"
        ]

        if (
            "peak_probability"
            in name_to_output
        ):
            peak_probability = (
                name_to_output[
                    "peak_probability"
                ]
                .ravel()
            )

    else:

        scaled = outputs

    raw_prediction = (
        power_scaler
        .inverse_transform(
            np.asarray(
                scaled
            ).reshape(-1, 1)
        )
        .ravel()
    )

    clipped_fraction = float(
        np.mean(
            raw_prediction < 0
        )
    )

    prediction_kw = np.maximum(
        raw_prediction,
        0.0
    )

    return (
        prediction_kw,
        peak_probability,
        clipped_fraction,
    )


